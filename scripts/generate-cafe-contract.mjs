import {readFile,writeFile} from 'node:fs/promises';
import ts from 'typescript';
// Workspace runtime exports must reference JavaScript for Node/Vercel tracing.
for(const name of ['cafe-options','restaurant']){
 const source=await readFile(`packages/contracts/src/${name}.ts`,'utf8');
 const {outputText}=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}});
 await writeFile(`packages/contracts/src/${name}.js`,'// Generated by npm run contracts:generate. Do not edit.\n'+outputText);
}
